// Writes docs/state-trim-before-after.md: what the Jev state looked like before
// trimming and compacting, what it looks like now, and what each rule removes.
// Free: no API calls.
//
//   node scripts/trim-report.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ago, buildState, monthsAgo } from '../src/engine/state.ts';
import { conditionAction, procedureAction } from '../src/engine/trim.ts';
import type { CodeBook, Patient } from '../src/engine/types.ts';

const REPO = resolve(import.meta.dirname, '../..');
const asOf = new Date('2026-10-10');
const bundle = JSON.parse(readFileSync(resolve(REPO, 'data/synthea-nj.json'), 'utf8'));
const codes: CodeBook = bundle.codes;
const patients: Patient[] = bundle.patients.map((p: Record<string, unknown>) => ({
  id: p.id, practice_id: '', birth_date: p.birthDate, sex: p.sex, record: p,
}));

// The state as it was before trimming (verbose objects, every entry), for comparison.
function beforeState(p: Patient) {
  const r = p.record;
  const long = (m: number) => (m < 1 ? 'this month' : m < 24 ? `about ${m} month${m === 1 ? '' : 's'} ago` : `about ${Math.round(m / 12)} years ago`);
  const n = (b: Record<string, string>, c: string) => b[c] ?? `code ${c}`;
  return {
    age: p.birth_date, sex: p.sex,
    conditions: r.conditions.map(([c, s, e]) => ({ name: n(codes.snomed, c), status: e ? 'resolved' : 'active', first_recorded: long(monthsAgo(s, asOf)), ...(e ? { ended: long(monthsAgo(e, asOf)) } : {}) })),
    medications: r.medications.map(([c, s, e]) => ({ name: n(codes.rxnorm, c), status: e ? 'stopped' : 'active', started: long(monthsAgo(s, asOf)), ...(e ? { stopped: long(monthsAgo(e, asOf)) } : {}) })),
    procedures: r.procedures.map(([c, l]) => ({ name: n(codes.snomed, c), most_recent: long(monthsAgo(l, asOf)) })),
    latest_labs_and_vitals: Object.entries(r.observations).map(([f, o]) => ({ name: f.replace(/_/g, ' '), value: o.value, ...(o.unit ? { unit: o.unit } : {}), measured: long(monthsAgo(o.date, asOf)) })),
    weights_last_year: (r.weights ?? []).map(([d, kg]) => ({ kg, measured: long(monthsAgo(d, asOf)) })),
    emergency_urgent_and_hospital_visits_last_3_years: (r.acuteVisits ?? []).map(([d, k, desc, rs]) => ({ kind: k, description: desc, reason: rs ?? 'not recorded', when: long(monthsAgo(d, asOf)) })),
  };
}

const size = (x: unknown) => JSON.stringify(x).length;
const TOKENS_PER_CHAR = 1 / 2.5;
const esc = (s: string) => s.replace(/\|/g, '\\|');

// ---- aggregate over every patient ----
const befores = patients.map((p) => size(beforeState(p))).sort((a, b) => a - b);
const afters = patients.map((p) => size(buildState(p, codes, asOf))).sort((a, b) => a - b);
const q = (xs: number[], f: number) => xs[Math.floor(f * (xs.length - 1))];

const dropCounts = new Map<string, Map<string, number>>(); // reason → name → patients
for (const p of patients) {
  const seen = new Set<string>();
  for (const [c] of p.record.conditions) {
    const name = codes.snomed[c] ?? c;
    const why = conditionAction(name);
    if (why !== 'keep' && !seen.has(name)) { seen.add(name); bump(why, name); }
  }
  for (const [c, l] of p.record.procedures) {
    const name = codes.snomed[c] ?? c;
    const why = procedureAction(name, monthsAgo(l, asOf));
    if (why !== 'keep' && !seen.has(name)) { seen.add(name); bump(why, name); }
  }
}
function bump(why: string, name: string) {
  const m = dropCounts.get(why) ?? new Map<string, number>();
  m.set(name, (m.get(name) ?? 0) + 1);
  dropCounts.set(why, m);
}

// ---- sample patients: one per interesting condition, first match in file order ----
const has = (p: Patient, re: RegExp) => p.record.conditions.some(([c]) => re.test(codes.snomed[c] ?? ''));
const picks: [string, Patient][] = [];
for (const [label, re] of [
  ['Asthma', /^asthma/i],
  ['COPD / emphysema', /emphysema|chronic obstructive/i],
  ['Obesity + diabetes', /diabetes mellitus type 2/i],
  ['Lung cancer', /non-small cell/i],
] as const) {
  const p = patients.find((x) => has(x, re) && !picks.some(([, y]) => y.id === x.id));
  if (p) picks.push([label, p]);
}

// ---- markdown ----
const lines: string[] = [];
const out = (s = '') => lines.push(s);

out('# Patient state: before and after trimming');
out();
out('Generated by `site/scripts/trim-report.ts` from `data/synthea-nj.json` (synthetic Synthea patients). No API calls.');
out();
out('**What changed:** each item is now one short line instead of a JSON object (most of the saving). Social/admin findings and visit boilerplate (forms filled in, referrals, discharge steps) are dropped. Dental work is folded into one line. Lab orders are kept and labelled "test ordered, no result on file". Pregnancy entries, dental conditions and minor acute illnesses are all kept. Rules: `site/src/engine/trim.ts`. Code-evaluated criteria are not affected.');
out();
out('## All 2,000 patients');
out();
out('| | Before | After | Change |');
out('|---|---|---|---|');
for (const [label, f] of [['Median', 0.5], ['90th percentile', 0.9], ['Largest', 1]] as const) {
  const b = q(befores, f), a = q(afters, f);
  out(`| ${label} | ${b.toLocaleString()} chars (~${Math.round(b * TOKENS_PER_CHAR).toLocaleString()} tokens) | ${a.toLocaleString()} chars (~${Math.round(a * TOKENS_PER_CHAR).toLocaleString()} tokens) | −${Math.round(100 * (1 - a / b))}% |`);
}
out();
out('## What each rule removes (across all patients)');
out();
for (const [why, m] of dropCounts) {
  const rows = [...m].sort((a, b) => b[1] - a[1]);
  out(`<details><summary><b>${why.replace('drop:', 'removed: ')}</b>: ${rows.length} distinct entries</summary>`);
  out();
  out('| Entry | Patients |');
  out('|---|---|');
  for (const [name, n] of rows) out(`| ${esc(name)} | ${n} |`);
  out();
  out('</details>');
  out();
}

for (const [label, p] of picks) {
  const r = p.record;
  const before = beforeState(p);
  const after = buildState(p, codes, asOf);
  out(`## Patient: ${label} (${after.age}, ${after.sex})`);
  out();
  out(`Size: **${size(before).toLocaleString()} → ${size(after).toLocaleString()} chars** (−${Math.round(100 * (1 - size(after) / size(before)))}%)`);
  out();

  // Item-by-item diff for the two trimmed sections.
  for (const [section, items] of [
    ['Conditions', r.conditions.map(([c, s, e]) => {
      const name = codes.snomed[c] ?? c;
      const action = conditionAction(name);
      const why = action === 'keep' ? null : action.replace('drop:', '');
      const kept = `${name.replace(/\s*\([a-z/ ]+\)\s*$/, '')} (${e ? `resolved, ${ago(monthsAgo(s, asOf))}–${ago(monthsAgo(e, asOf))}` : `active, since ${ago(monthsAgo(s, asOf))}`})`;
      return [name, why ? `~~removed~~ (${why})` : `\`${kept}\``] as const;
    })],
    ['Procedures', r.procedures.map(([c, l]) => {
      const name = codes.snomed[c] ?? c;
      const m = monthsAgo(l, asOf);
      const action = procedureAction(name, m);
      const short = name.replace(/\s*\([a-z/ ]+\)\s*$/, '');
      const after =
        action === 'keep' ? `\`${short} (${ago(m)})\``
        : action === 'lab order' ? `\`${short} (${ago(m)}; test ordered, no result on file)\``
        : action === 'dental summary' ? 'folded into `Routine dental care (most recent …)`'
        : `~~removed~~ (${action.replace('drop:', '')})`;
      return [`${name}, ${m} months ago`, after] as const;
    })],
  ] as const) {
    const removed = items.filter(([, a]) => a.startsWith('~~') || a.startsWith('folded')).length;
    const folded = items.some(([, a]) => a.startsWith('folded')) ? ' (+1 dental summary line)' : '';
    out(`<details open><summary><b>${section}</b>: ${items.length} before → ${items.length - removed} after${folded}</summary>`);
    out();
    out('| Before | After |');
    out('|---|---|');
    for (const [b, a] of items) out(`| ${esc(b)} | ${esc(a)} |`);
    out();
    out('</details>');
    out();
  }

  out('<details><summary><b>Full state Jev now receives</b></summary>');
  out();
  out('```json');
  out(JSON.stringify(after, null, 1));
  out('```');
  out('</details>');
  out();
  out('<details><summary>Full state before (for reference)</summary>');
  out();
  out('```json');
  out(JSON.stringify({ ...before, age: '(age)' }, null, 1));
  out('```');
  out('</details>');
  out();
}

const path = resolve(REPO, 'docs/state-trim-before-after.md');
writeFileSync(path, lines.join('\n'));
console.log(`Wrote ${path}`);
console.log(`median ${q(befores, 0.5)} → ${q(afters, 0.5)} chars, p90 ${q(befores, 0.9)} → ${q(afters, 0.9)}`);
